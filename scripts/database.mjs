import 'dotenv/config';
import EmbeddedPostgres from 'embedded-postgres';
import {existsSync,mkdirSync} from 'node:fs';
import path from 'node:path';
const url=new URL(process.env.DATABASE_URL);
if(!['localhost','127.0.0.1'].includes(url.hostname))throw new Error('The local database helper only starts a loopback database.');
const databaseDir=process.env.DATABASE_DIR||path.resolve('.runtime/postgres');
mkdirSync(databaseDir,{recursive:true});
const db=new EmbeddedPostgres({databaseDir,user:url.username,password:url.password,port:Number(url.port),persistent:true,authMethod:'scram-sha-256',postgresFlags:['-h','127.0.0.1'],onLog:()=>{},onError:()=>{}});
if(!existsSync(path.join(databaseDir,'PG_VERSION')))await db.initialise();
await db.start();
const client=db.getPgClient();await client.connect();
const name=url.pathname.slice(1);
if(!/^[a-z][a-z0-9_]*$/.test(name))throw new Error('Invalid local database name.');
if(!(await client.query('SELECT 1 FROM pg_database WHERE datname=$1',[name])).rowCount)await db.createDatabase(name);
await client.end();
console.log(`Aura PostgreSQL ready on 127.0.0.1:${url.port}`);
for(const signal of ['SIGINT','SIGTERM'])process.on(signal,async()=>{await db.stop();process.exit(0);});
setInterval(()=>{},60000);
